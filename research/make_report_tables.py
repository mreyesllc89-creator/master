#!/usr/bin/env python3
"""Refresh the data-driven parts of research/reports/loma_oos_review.html (sections 1 to 3 and the tiles) from
research/results/loma_report_data.json: the section-1 table and note, the monthly chart array, the two-period
table and the Dukascopy table. Section 5 is written by make_recal_html.py. Run from the repository root."""
import json, re

PAGE = "research/reports/loma_oos_review.html"
d = json.load(open("research/results/loma_report_data.json"))
P = d["presets"]; per = {x["period"]: x for x in d["vt_periods"]}
LABEL = {"Top01": "Top01 · M10 Both", "Top02": "Top02 · M3 Sell", "Top03": "Top03 · M2 Sell", "Top04": "Top04 · M5 Both",
         "Top05": "Top05 · M10 Buy", "Top07": "Top07 · M5 Buy"}


def money(v, sign=True):
    s = f"{abs(v):,.0f}"
    return ("−" if v < 0 else "+" if sign else "") + s


def cls(v):
    return ' class="loss"' if v < 0 else ' class="gain"'


s = open(PAGE, encoding="utf-8").read()

# ---- section 1: table and note
w = per["whole run"]
rows = "\n".join(
    f'          <tr><td>{LABEL[p["preset"]]}</td><td>{p["bt_pf"]:.2f}</td><td>{p["bt_pf_2026"]:.2f}</td><td>{p["vt_trades"]}</td>'
    f'<td>{p["vt_gross_pf"]:.2f}</td><td>{p["vt_real_pf"]:.2f}</td><td{cls(p["vt_real_net"])}>{money(p["vt_real_net"])}</td>'
    f'<td{cls(p["vt_net"])}>{money(p["vt_net"])}</td></tr>' for p in P)
tot_trades = sum(p["vt_trades"] for p in P)
s1 = f"""<!-- s1:start (generated by research/make_report_tables.py) -->
    <div class="tablebox">
      <table>
        <thead><tr>
          <th>Preset</th><th>Backtest PF<span class="sub">2025 – May 2026</span></th><th>Backtest PF<span class="sub">2026 part</span></th>
          <th>VT trades</th><th>VT PF<span class="sub">before commission</span></th><th>VT PF<span class="sub">at $0.60 per lot</span></th>
          <th>VT net<span class="sub">at $0.60 per lot</span></th><th>VT net<span class="sub">at the tester's $6 per lot</span></th>
        </tr></thead>
        <tbody>
{rows}
          <tr class="total"><td>All six</td><td></td><td></td><td>{tot_trades}</td><td>{w["gross_pf"]:.2f}</td><td>{w["real_net_pf"]:.2f}</td><td class="loss">{money(w["real_net"])}</td><td class="loss">{money(d["vt_total"]["net"])}</td></tr>
        </tbody>
      </table>
    </div>
    <p class="note">Dollar figures are US$ on a $10,000 test deposit per preset. The Strategy Tester charged $6 per lot round trip (1 lot = 1 ounce): {money(d["vt_total"]["comm"], False)} in all. VT's real commission is $0.60 per lot, as the account owner reported it, which makes {money(w["real_comm"], False)}. The before-commission column does not depend on the commission. The profit factor at $0.60 charges both commission legs to each round trip. MT5's own report, at its $6 rate and counted per deal, shows 0.50, 0.55, 0.40, 0.36, 0.45 and 0.33.</p>
<!-- s1:end -->"""
if "<!-- s1:start" in s:
    s = re.sub(r"<!-- s1:start.*?<!-- s1:end -->", lambda m: s1, s, flags=re.S)
else:
    m = re.search(r'    <div class="tablebox">\n      <table>\n        <thead><tr>\n          <th>Preset</th><th>Backtest PF.*?</table>\n    </div>\n    <p class="note">Dollar figures.*?</p>', s, flags=re.S)
    assert m, "section 1 block not found"
    s = s[:m.start()] + s1 + s[m.end():]

# ---- tiles
s, n = re.subn(r'<div class="tile"><span class="v loss">−\$[\d,]+</span><span class="k">VT net at its real \$0\.60.*?</span></div>',
               f'<div class="tile"><span class="v loss">−${abs(w["real_net"]):,.0f}</span><span class="k">VT net at its real $0.60 commission per lot, six presets, '
               f'{tot_trades} trades (−${abs(d["vt_total"]["net"]):,.0f} at the tester\'s $6)</span></div>', s, flags=re.S)
assert n == 1
duk = {(x["preset"], x["period"]): x for x in d["dukascopy"]}
tm = duk[("All six", "Jun-Aug")]["matched"] + duk[("All six", "Sep-Nov 6")]["matched"]
tv = duk[("All six", "Jun-Aug")]["vt_n"] + duk[("All six", "Sep-Nov 6")]["vt_n"]
s, n = re.subn(r'<span class="v">\d+ / \d+</span><span class="k">VT trades that Dukascopy also found', f'<span class="v">{tm} / {tv}</span><span class="k">VT trades that Dukascopy also found', s)
assert n == 1

# ---- monthly chart: gross and commission at the real rate
scale = d["vt_commission"]["real_per_lot_round_trip"] / d["vt_commission"]["tester_per_lot_round_trip"]
names = {"03": "Mar", "04": "Apr", "05": "May", "06": "Jun", "07": "Jul", "08": "Aug", "09": "Sep", "10": "Oct", "11": "Nov*"}
arr = ", ".join(f'["{names[x["month"][-2:]]}", {x["gross"]:.2f}, {scale * x["comm"]:.2f}]' for x in d["vt_monthly"])
s, n = re.subn(r"var months = \[.*?\];", lambda m: f"var months = [\n    {arr}\n  ];", s, flags=re.S)
assert n == 1

# ---- two-period table
a, b = per["Mar-May"], per["Jun-Nov 6"]
for x, sub in ((a, "overlaps the fitting data"), (b, "untouched")):
    pat = re.compile(r'(<span class="sub">%s</span></td>)<td>\d+</td><td class="(?:gain|loss)">[^<]*</td><td>[\d.]+</td><td>[\d.]+</td><td>[\d.]+</td></tr>' % re.escape(sub))
    new = (r'\g<1>' + f'<td>{x["trades"]}</td><td{cls(x["gross"])}>{money(x["gross"])}</td><td>{x["gross_pf"]:.2f}</td>'
           f'<td>{x["real_net_pf"]:.2f}</td><td>{x["net_pf"]:.2f}</td></tr>')
    s, n = pat.subn(new, s)
    assert n == 1, sub

# ---- Dukascopy table
def sgn(v):
    return ("+" if v > 0 else "−" if v < 0 else "") + f"{abs(v):.1f}R"


def cells(p, period):
    x = duk[(p, period)]
    return (f'<td>{x["duk_n"]} · {x["duk_pf"]:.2f} · {sgn(x["duk_netR"])}</td><td>{x["vt_n"]} · {x["vt_gross_pf"]:.2f}</td>'
            f'<td>{x["matched"]}/{x["vt_n"]}</td>')


for p, label in [("Top01", "Top01 · M10"), ("Top02", "Top02 · M3"), ("Top03", "Top03 · M2"), ("Top04", "Top04 · M5"),
                 ("Top05", "Top05 · M10"), ("Top07", "Top07 · M5"), ("All six", "All six")]:
    c = ' class="total"' if p == "All six" else ""
    pat = re.compile(r"<tr%s><td>%s</td>.*?</tr>" % (re.escape(c), re.escape(label)))
    m = [x for x in pat.finditer(s) if re.search(r"<td>\d+/\d+</td>", x.group(0))]
    assert len(m) == 1, (p, len(m))
    s = s.replace(m[0].group(0), f"<tr{c}><td>{label}</td>{cells(p, 'Jun-Aug')}{cells(p, 'Sep-Nov 6')}</tr>")

open(PAGE, "w", encoding="utf-8").write(s)
t2 = duk[("Top02", "Sep-Nov 6")]
print(f"report tables refreshed: real net {w['real_net']:.0f}, matched {tm}/{tv}, Top02 Sep-Nov Dukascopy {t2['duk_pf']:.2f} vs VT {t2['vt_gross_pf']:.2f}")
