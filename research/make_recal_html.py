#!/usr/bin/env python3
"""Write the "Re-calibration per timeframe" section of research/reports/loma_oos_review.html from
research/results/recal/*.json (between the recal:start / recal:end markers; inserted before the
"What this means" section on the first run). Run from the repository root."""
import json, re
import pandas as pd

R = "research/results/recal"
PAGE = "research/reports/loma_oos_review.html"
TFS = ["M1", "M2", "M3", "M5", "M10", "M15", "M30", "H1"]
FAMILY = {"none": "No trailing", "R": "Multiples of the risk (the EA's own)", "points": "Fixed distance in dollars",
          "percent": "Percent of price", "atr": "ATR multiple (chandelier)", "breakeven": "Breakeven",
          "step": "Stepped ratchet", "candles": "Candle highs / lows", "ema": "Moving average (EMA)",
          "psar": "Parabolic SAR", "hump": "Hump structure"}


def load(name):
    return json.load(open(f"{R}/{name}.json"))


def tfrows(sym, run):
    return {x["tf"]: x for x in load(f"{sym}_{run}")["timeframes"]}


def cell(x, stress=True, vt=None):
    if not x or not x.get("picked"):
        return '<td class="mut">none passed in-sample</td>'
    cls = ' class="gain"' if x["oos_pf"] >= 1.3 and x["oos_n"] >= 100 else ""
    sub = []
    if stress:
        sub.append(f'stressed {x["oos_stress_pf"]:.2f}')
    if vt and vt.get("picked"):
        sub.append(f'VT costs {vt["vt_oos_pf"]:.2f}')
    s = f' <span class="sub">{" · ".join(sub)}</span>' if sub else ""
    return f'<td{cls}>{x["oos_pf"]:.2f} ({int(x["oos_n"])}){s}</td>'


g1, g2, b1, b2 = tfrows("xauusd", "r_trailing"), tfrows("xauusd", "all_trailing"), tfrows("btcusd", "r_trailing"), tfrows("btcusd", "all_trailing")
v1 = {x["tf"]: x for x in load("xauusd_r_trailing_vt_costs")["timeframes"]}
v2 = {x["tf"]: x for x in load("xauusd_all_trailing_vt_costs")["timeframes"]}
vt_all = [x["vt_oos_pf"] for d in (v1, v2) for x in d.values() if x.get("picked")]
rows = "\n".join(f"          <tr><td>{tf}</td>{cell(g1.get(tf), False, v1.get(tf))}{cell(g2.get(tf), True, v2.get(tf))}"
                 f"{cell(b1.get(tf), False)}{cell(b2.get(tf))}</tr>" for tf in TFS)
passes = sum(1 for d in (g1, g2, b1, b2) for x in d.values() if x.get("passes"))

kg = {x["kind"]: x for x in load("xauusd_all_trailing_by_family")["by_kind_all_timeframes"]}
kb = {x["kind"]: x for x in load("btcusd_all_trailing_by_family")["by_kind_all_timeframes"]}
order = sorted(FAMILY, key=lambda k: -(kg[k]["oos_pf"] + kb[k]["oos_pf"]))
fam = "\n".join(f'          <tr><td>{FAMILY[k]}</td><td>{kg[k]["oos_pf"]:.2f} ({kg[k]["oos_n"]})</td><td>{kg[k]["oos_stress_pf"]:.2f}</td>'
                f'<td>{kb[k]["oos_pf"]:.2f} ({kb[k]["oos_n"]})</td><td>{kb[k]["oos_stress_pf"]:.2f}</td></tr>' for k in order)

cells = pd.concat([pd.DataFrame(load(f"{s}_all_trailing_by_family")["cells"]) for s in ("xauusd", "btcusd")])
big = cells[cells.oos_n >= 100]
n_cells, n_pass = len(big), int((big.oos_pf >= 1.3).sum())
passing = "; ".join(f'{"gold" if r.symbol == "XAUUSD" else "BTC"} {r.tf} with {FAMILY[r.kind].split(" (")[0].lower()} trailing, '
                    f'{r.oos_pf:.2f} on {int(r.oos_n)} trades' for r in big[big.oos_pf >= 1.3].itertuples())

pre = {x["group"]: x for x in load("btcusd_picks_on_2023_2024")}


def prerow(label, key):
    x = pre[key]
    return (f'          <tr><td>{label}</td><td>{x["oos2026_pf"]:.2f} ({x["oos2026_n"]})</td><td>{x["y2024_pf"]:.2f} ({x["y2024_n"]})</td>'
            f'<td>{x["y2023_pf"]:.2f} ({x["y2023_n"]})</td></tr>')


pretab = "\n".join([prerow("BTC, moving-average trailing: 10 setups", "trailing ema"),
                    prerow("BTC M10 with moving-average trailing: 4 setups", "M10 + ema trailing"),
                    prerow("BTC M5, best 10 of any trailing", "timeframe M5"),
                    prerow("BTC M1, the single setup that passed in-sample", "timeframe M1")])
y24 = [x["y2024_pf"] for x in pre.values()]; y23 = [x["y2023_pf"] for x in pre.values()]

section = f"""<!-- recal:start (generated by research/make_recal_html.py from research/results/recal/*.json) -->
  <section>
    <span class="eyebrow">5 · Re-calibration per timeframe</span>
    <h2>No timeframe holds PF 1.3 on unseen data, with any trailing stop</h2>
    <p>After the six presets failed, the calibration was redone for every timeframe from M1 to H1, on gold and on BTC, with part of the data held back. Each setup was scored on January 2025 – 15 May 2026 only: the lowest of six profit factors (three periods, each at normal and at stressed costs, at least 20 trades per period). The 10 best setups of each timeframe, one per direction, session and trend-filter combination and only with a score of 1.3 or more, were then run unchanged on 16 May – 13 November 2026. A timeframe passes with a profit factor of 1.3 or more on at least 100 of those unseen trades.</p>
    <p>Run 1 used the EA's own trailing stop (multiples of the risk): 12,000 random setups per timeframe. Run 2 added ten more trailing families: 33,000 setups per timeframe.</p>
    <div class="tablebox">
      <table>
        <thead><tr><th>Timeframe</th><th>Gold, run 1<span class="sub">unseen PF (trades)</span></th><th>Gold, run 2: every trailing<span class="sub">unseen PF (trades)</span></th>
          <th>BTC, run 1<span class="sub">unseen PF (trades)</span></th><th>BTC, run 2: every trailing<span class="sub">unseen PF (trades)</span></th></tr></thead>
        <tbody>
{rows}
        </tbody>
      </table>
    </div>
    <p class="note">{passes} of 32 pass. Stressed = entry one minute late, pessimistic trailing, slippage and commission. VT costs = the same gold setups at VT Markets' own costs as the account owner reported them, a 1.5-pip spread ($0.15) and $0.60 commission per lot, $0.75 per ounce in all: {min(vt_all):.2f} to {max(vt_all):.2f}. BTC M1 in run 2 rests on one setup with 77 trades, under the 100-trade minimum. Gold: FTMO prices to 15 May 2026, Dukascopy after; BTC: Binance.</p>
    <h3>By trailing family, all timeframes together (run 2)</h3>
    <div class="tablebox">
      <table>
        <thead><tr><th>Trailing family</th><th>Gold<span class="sub">unseen PF (trades)</span></th><th>Gold stressed</th><th>BTC<span class="sub">unseen PF (trades)</span></th><th>BTC stressed</th></tr></thead>
        <tbody>
{fam}
        </tbody>
      </table>
    </div>
    <p>No trailing family rescues gold: the best is no trailing at all. Split by timeframe and trailing family there are {n_cells} combinations with at least 100 unseen trades, and {n_pass} reach 1.3 ({passing}), about what chance alone gives. The one pattern, moving-average trailing on BTC, was checked on a second untouched period, 2023 and 2024, which lie before the calibration data:</p>
    <div class="tablebox">
      <table>
        <thead><tr><th>Setups picked on Jan 2025 – May 2026</th><th>Unseen 2026<span class="sub">PF (trades)</span></th><th>2024<span class="sub">PF (trades)</span></th><th>2023<span class="sub">PF (trades)</span></th></tr></thead>
        <tbody>
{pretab}
        </tbody>
      </table>
    </div>
    <p class="note">Across all 20 groups of BTC picks (8 timeframes, 11 trailing families and the M10 moving-average group) the 2024 profit factor ranges from {min(y24):.2f} to {max(y24):.2f} and the 2023 one from {min(y23):.2f} to {max(y23):.2f}. The moving-average result of 2026 did not repeat, so it is not counted as an edge. In 2023 BTC traded at about a third of its 2025–26 price, which makes the fixed $10 spread relatively dearer.</p>
  </section>
<!-- recal:end -->
"""

s = open(PAGE, encoding="utf-8").read()
if "<!-- recal:start" in s:
    s = re.sub(r"<!-- recal:start.*?<!-- recal:end -->\n", lambda m: section, s, flags=re.S)
else:
    anchor = '  <section>\n    <span class="eyebrow">5 · What this means</span>'
    assert s.count(anchor) == 1
    s = s.replace(anchor, section + '\n  <section>\n    <span class="eyebrow">6 · What this means</span>')
open(PAGE, "w", encoding="utf-8").write(s)
print("section written:", passes, "of 32 pass;", n_cells, "cells,", n_pass, "reach 1.3:", passing)
